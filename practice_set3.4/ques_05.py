student = {
    "Roll": 101,
    "Name": "Rahul",
    "Branch": "CSE",
    "Sem": 5
}

# Print all keys
print("Keys:", student.keys())

# Print all values
print("Values:", student.values())

# Print all key-value pairs
print("Key-value pairs:", student.items())


# output:
# Keys: dict_keys(['Roll', 'Name', 'Branch', 'Sem'])
# Values: dict_values([101, 'Rahul', 'CSE', 5])
# Key-value pairs: dict_items([('Roll', 101), ('Name', 'Rahul'), ('Branch', 'CSE'), ('Sem', 5)])