# Q4. Create a complex number using both 'a+bj' notation and the complex() function. Also print the real and imaginary parts of a complex number.


#  using a+bj notation

c1 = 5+3j

# using complex() function

c2 = complex(5, 3)

print("Complex number 1 =",c1)
print("Complex number 2 =",c2)

# Real and imaginary parts
print("Real part =", c1.real)
print("Imaginary part =", c1.imag)