c1 = 6 + 9j
c2 = 4 - 7j

# Addition
addition = c1 + c2

# Multiplication
multiplication = c1 * c2

# Magnitude / Absolute value
magnitude_c1 = abs(c1)
magnitude_c2 = abs(c2)

# Print results and data types
print("Addition:", addition)
print("Data type of addition:", type(addition))

print("Multiplication:", multiplication)
print("Data type of multiplication:", type(multiplication))

print("Magnitude of c1:", magnitude_c1)
print("Data type of magnitude c1:", type(magnitude_c1))

print("Magnitude of c2:", magnitude_c2)
print("Data type of magnitude c2:", type(magnitude_c2))

# Memory addresses
print("Memory address of c1:", id(c1))
print("Memory address of c2:", id(c2))