# Q3. Concatenate two tuples and display the result. Also, repeat a tuple three times.


tuple1 = (10, 20, 30)
tuple2 = (40, 50, 60)
result = tuple1 + tuple2
print("Concatenated tuple:", result)
print("Repeated tuple:", tuple1 * 3)


# output:
# Concatenated tuple: (10, 20, 30, 40, 50, 60)
# Repeated tuple: (10, 20, 30, 10, 20, 30, 10, 20, 30)