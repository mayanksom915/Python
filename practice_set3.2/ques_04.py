numbers = (10, 20, 30, 40, 50)
print("Reversed tuple:", numbers[::-1])
print("Maximum:", max(numbers))
print("Minimum:", min(numbers))
print("Sum:", sum(numbers))
average = sum(numbers) / len(numbers)
print("Average:", average)


