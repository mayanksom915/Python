# 4. Create variables of type int, float, str, bool, and display their data types using type().

int = 18
str = "mayank"
float = 1.8
bool = True

print("Value of int : ",int)
print("Type of int : ",type(int))
print("Value of str : ",str)
print("Type of str : ",type(str))
print("Value of float : ",float)
print("Type of float : ",type(float))
print("Value of bool : ",bool)
print("Type of bool : ",type(bool))
